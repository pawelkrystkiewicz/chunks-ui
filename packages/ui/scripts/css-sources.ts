/**
 * Writes the stylesheets that let an app generate the CSS of only the components it uses. The
 * ESM build calls writeCssSources from its onSuccess (tsup.config.ts), after it copies theme.css:
 * - dist/theme.core.css: theme.css without its `@source "./";`, which scans all of dist/;
 * - dist/sources/<name>.css: one `@source` per file of dist/ that holds the code of <name>
 *   (`chunks-ui/sources/button.css`), for each component folder and for utils.
 * The default setup, theme.css alone, stays as it is. Node APIs only: tsup runs this on Node.
 *
 * Tests: css-sources.spec.ts (fixture dists in a temporary directory)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, posix } from "node:path";

/**
 * The output of the utils build, a separate tsup config that may still be writing it when the
 * ESM build's onSuccess runs. The walk lists it without reading it; it imports nothing relative.
 */
const UTILS = "utils.js";
const SOURCE = '@source "./";';

// `import … from`, `export … from` and a bare `import "./x.js"`. esbuild puts each import and
// export statement at the start of a line
const STATIC = /^[ \t]*(?:(?:import|export)\b[^;"'`]*?\bfrom|import)\s*["'](\.{1,2}\/[^"']*)["']/gm;
const DYNAMIC = /\bimport\s*\(\s*(?:\/\*[\s\S]*?\*\/\s*)*["'`](\.{1,2}\/[^"'`]*)["'`]/g;
const COMMENTS = /\/\*[\s\S]*?\*\//g;

/** The relative specifiers that `code` imports or re-exports statically, and dynamically */
export function relativeImports(code: string): { static: string[]; dynamic: string[] } {
  const specifiers = (pattern: RegExp) => [...code.matchAll(pattern)].map(([, path = ""]) => path);
  return {
    static: specifiers(STATIC),
    dynamic: specifiers(DYNAMIC),
  };
}

/**
 * The files of `dist` that `entry` loads: itself and every file it imports or re-exports, with
 * static relative imports, transitively. Paths are relative to `dist`, sorted. Throws on a file
 * that does not exist, an import out of `dist`, and a relative dynamic import, which would load
 * code whose classes the stylesheet would miss.
 * ponytail: every closure holds utils.js, which has the variants of Button, Chip, IconButton and
 * Input. A component that uses none of them gets all four sets: about 120 rules (~1.6 KB gzip).
 * button.css, whose own classes are there anyway, pays for the other three sets: about 35 rules
 * (~0.35 KB gzip). Goes when the utils build is split, so the walk can follow only the variant
 * modules a component imports.
 */
export function closure(dist: string, entry: string): string[] {
  const seen = new Set<string>();
  const walk = (file: string) => {
    if (seen.has(file)) return;
    seen.add(file);
    if (file === UTILS) return;
    const code = readFileSync(join(dist, file), "utf8");
    const imports = relativeImports(code);
    const [lazy] = imports.dynamic;
    if (lazy !== undefined) {
      throw new Error(
        `${file} imports "${lazy}" dynamically: the CSS sources follow static imports only, so its classes would be missing`,
      );
    }
    for (const specifier of imports.static) {
      const target = posix.join(posix.dirname(file), specifier);
      if (target.startsWith("../")) {
        throw new Error(`${file} imports "${specifier}", outside ${dist}`);
      }
      if (target !== UTILS && !existsSync(join(dist, target))) {
        throw new Error(`${file} imports "${specifier}", which is not in ${dist}`);
      }
      walk(target);
    }
  };
  walk(entry);
  return [...seen].sort();
}

/** dist/sources/<name>.css: a `@source` for each of `files` (paths relative to dist/) */
export function sourcesCss(name: string, files: string[]): string {
  const lines = [...new Set(files)].sort().map((file) => `@source "../${file}";`);
  return `/* Generated by the chunks-ui build: the files that hold the classes of ${name}. */\n${lines.join("\n")}\n`;
}

const HEADER = `/*
 * chunks-ui's theme without the scan of its components: Tailwind generates no component classes
 * from it. Import chunks-ui/sources/<component>.css for each component the app renders.
 * Generated from theme.css by the chunks-ui build.
 */`;

/**
 * dist/theme.core.css: `theme`, the source of theme.css, with its `@source "./";` and the comment
 * right above it swapped for HEADER. Throws unless `theme` has that line exactly once, and when
 * the result still has an `@source`.
 */
export function themeCore(theme: string): string {
  const count = theme.split(SOURCE).length - 1;
  if (count !== 1) {
    throw new Error(
      `theme.css has ${count} lines \`${SOURCE}\`, not 1: update scripts/css-sources.ts`,
    );
  }
  // The comment right above the line: one that holds no "*/" of its own
  const core = theme.replace(/(?:\/\*(?:(?!\*\/)[\s\S])*\*\/\s*)?@source "\.\/";/, HEADER);
  if (/@source\b/.test(core.replace(COMMENTS, ""))) {
    throw new Error("theme.core.css still has an @source: it must scan nothing");
  }
  return core;
}

/**
 * Writes `dist`/theme.core.css from `theme` and `dist`/sources/<name>.css for each of `names`
 * (dist/<name>.js is its entry). Computes them all first, so a throw writes nothing.
 */
export function writeCssSources(dist: string, theme: string, names: string[]) {
  const core = themeCore(theme);
  const sources = names.map(
    (name) => [name, sourcesCss(name, closure(dist, `${name}.js`))] as const,
  );
  writeFileSync(join(dist, "theme.core.css"), core);
  mkdirSync(join(dist, "sources"), { recursive: true });
  for (const [name, css] of sources) writeFileSync(join(dist, "sources", `${name}.css`), css);
}
